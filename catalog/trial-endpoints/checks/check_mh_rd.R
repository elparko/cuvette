cat(sprintf("MH risk difference %.6f CI %.6f %.6f\n", m$TE.common, m$lower.common, m$upper.common))
m <- metabin(a, n1, c0, n0, sm = "RR", method = "MH", common = TRUE, random = FALSE, incr = 0, allstudies = TRUE, MH.exact = TRUE)
cat(sprintf("MH risk ratio %.6f CI %.6f %.6f\n", exp(m$TE.common), exp(m$lower.common), exp(m$upper.common)))
