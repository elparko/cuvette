here <- commandArgs(trailingOnly = TRUE)[1]
cat(R.version.string, "\n\n")
f3 <- function(x) formatC(x, digits = 6, format = "f")

cat("== Logistic regression, Hosmer and Lemeshow low birth weight data (MASS birthwt)\n")
b <- read.csv(file.path(here, "data", "birthwt.csv"))
b$race <- factor(b$race)
m <- glm(low ~ age + lwt + race + ftv, family = binomial, data = b)
print(round(coef(summary(m)), 6))
cat("log-likelihood", f3(logLik(m)), "\n")
ci <- confint.default(m)
print(round(cbind(OR = exp(coef(m)), lo = exp(ci[, 1]), hi = exp(ci[, 2])), 6))
m0 <- glm(low ~ 1, family = binomial, data = b)
g <- 2 * (logLik(m) - logLik(m0))
cat("likelihood-ratio G", f3(g), "df", m$rank - 1, "p", f3(pchisq(g, m$rank - 1, lower.tail = FALSE)), "\n")
print(drop1(m, test = "LRT"))

cat("\n== Logistic regression with a text factor, R infert data\n")
i <- read.csv(file.path(here, "data", "infert.csv"))
i$education <- factor(i$education, levels = c("0-5yrs", "12+ yrs", "6-11yrs"))
mi <- glm(case ~ education + spontaneous + induced, family = binomial, data = i)
print(round(coef(summary(mi)), 6))
ci <- confint.default(mi)
print(round(cbind(OR = exp(coef(mi)), lo = exp(ci[, 1]), hi = exp(ci[, 2])), 6))
print(drop1(mi, test = "LRT"))
cat("n", nobs(mi), "events", sum(i$case), "\n")

cat("\n== Logistic regression on a subset: birthwt smokers only, low ~ lwt\n")
ms <- glm(low ~ lwt, family = binomial, data = subset(b, smoke == 1))
print(round(coef(summary(ms)), 6))
cat("n", nobs(ms), "\n")

cat("\n== Chi-square, Agresti (2007) p 39 party by gender, R help of chisq.test\n")
M <- as.table(rbind(c(762, 327, 468), c(484, 239, 477)))
x <- chisq.test(M)
print(x)
print(round(x$expected, 4))
cat("\n== Chi-square 2x2, birthwt smoke by low, Yates and no correction\n")
t2 <- table(b$smoke, b$low)
print(t2)
print(chisq.test(t2))
print(chisq.test(t2, correct = FALSE))
print(round(chisq.test(t2)$expected, 4))
cat("\n== Chi-square with small expected counts, birthwt ftv by low\n")
t3 <- table(b$ftv, b$low)
print(t3)
x3 <- suppressWarnings(chisq.test(t3))
print(x3)
print(round(x3$expected, 4))
cat("cells below 5:", sum(x3$expected < 5), "of", length(x3$expected), "\n")

