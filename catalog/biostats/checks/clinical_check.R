cat("\n== Cox model with a text factor and a subset, veteran lung cancer data (Kalbfleisch and Prentice), R survival\n")
library(survival)
v <- read.csv(file.path(here, "data", "veteran.csv"))
v$celltype <- factor(v$celltype, levels = c("adeno", "large", "smallcell", "squamous"))
cx <- coxph(Surv(time, status) ~ trt + celltype + karno, data = v, ties = "efron")
print(round(coef(summary(cx)), 6))
cat("n", cx$n, "events", cx$nevent, "\n")
cs <- coxph(Surv(time, status) ~ trt + karno, data = subset(v, prior == 0), ties = "efron")
print(round(coef(summary(cs)), 6))
cat("n", cs$n, "events", cs$nevent, "\n")
