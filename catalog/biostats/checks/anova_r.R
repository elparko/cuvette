args <- commandArgs(trailingOnly = FALSE)
here <- dirname(normalizePath(sub("^--file=", "", args[grep("^--file=", args)])))
d <- file.path(here, "..", "data")
cat(R.version.string, "\n\n")

cat("## warpbreaks, two-way ANOVA: summary(aov(breaks ~ wool * tension))\n")
wb <- read.csv(file.path(d, "warpbreaks.csv"))
print(summary(aov(breaks ~ wool * tension, data = wb)))
cat("\n## Tukey on the six cells (wool:tension)\n")
print(TukeyHSD(aov(breaks ~ wool * tension, data = wb), "wool:tension")$"wool:tension"[1:4, ])

cat("\n## PlantGrowth, Kruskal-Wallis and Dunn (FSA, bonferroni)\n")
pg <- read.csv(file.path(d, "plantgrowth.csv"))
print(kruskal.test(weight ~ group, data = pg))
suppressMessages(library(FSA))
print(dunnTest(weight ~ factor(group), data = pg, method = "bonferroni")$res)

cat("\n## RoundingTimes (Hollander & Wolfe 1973 p.140), Friedman\n")
rt <- read.csv(file.path(d, "rounding_times.csv"))
m <- as.matrix(reshape(rt, idvar = "player", timevar = "method", direction = "wide")[, -1])
print(friedman.test(m))

cat("\n## sleepstudy, repeated measures over Days, aov with an error term\n")
ss <- read.csv(file.path(d, "sleepstudy.csv"))
ss$Days <- factor(ss$Days)
ss$Subject <- factor(ss$Subject)
print(summary(aov(Reaction ~ Days + Error(Subject / Days), data = ss)))

cat("\n## Hollander & Wolfe (1973) p.29 and p.69: wilcox.test exact\n")
x <- c(1.83, 0.50, 1.62, 2.48, 1.68, 1.88, 1.55, 3.06, 1.30)
y <- c(0.878, 0.647, 0.598, 2.05, 1.06, 1.29, 1.06, 3.14, 1.29)
print(wilcox.test(x, y, paired = TRUE, alternative = "greater"))
x2 <- c(0.80, 0.83, 1.89, 1.04, 1.45, 1.38, 1.91, 1.64, 0.73, 1.46)
y2 <- c(1.15, 0.88, 0.90, 0.74, 1.21)
print(wilcox.test(x2, y2, alternative = "greater"))
print(wilcox.test(x2, y2, alternative = "greater", exact = FALSE, correct = TRUE))
