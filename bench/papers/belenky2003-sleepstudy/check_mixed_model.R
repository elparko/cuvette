.libPaths(c("/Volumes/T7/guided-analysis/tools/R-library", .libPaths()))
suppressMessages(library(lme4))
d <- read.csv("/Volumes/T7/guided-analysis/data/belenky2003-sleepstudy/sleepstudy.csv")
d$Subject <- factor(d$Subject)
m_slope <- lmer(Reaction ~ Days + (Days | Subject), data = d, REML = TRUE)
m_int <- lmer(Reaction ~ Days + (1 | Subject), data = d, REML = TRUE)
m_ols <- lm(Reaction ~ Days, data = d)
fe <- coef(summary(m_slope))
vc <- as.data.frame(VarCorr(m_slope))
cat(R.version.string, "lme4", as.character(packageVersion("lme4")), "\n")
cat(sprintf("days_slope %.4f\n", fe["Days", "Estimate"]))
cat(sprintf("intercept %.4f\n", fe["(Intercept)", "Estimate"]))
cat(sprintf("se_days_random_slope %.4f\n", fe["Days", "Std. Error"]))
cat(sprintf("se_days_random_intercept_trap %.4f\n", coef(summary(m_int))["Days", "Std. Error"]))
cat(sprintf("se_days_ols_trap %.4f\n", coef(summary(m_ols))["Days", "Std. Error"]))
cat(sprintf("intercept_variance %.3f\n", vc$vcov[which(vc$grp == "Subject" & vc$var1 %in% "(Intercept)" & is.na(vc$var2))]))
cat(sprintf("slope_variance %.3f\n", vc$vcov[which(vc$var1 %in% "Days" & is.na(vc$var2))]))
cat(sprintf("residual_variance %.3f\n", vc$vcov[vc$grp == "Residual"]))
