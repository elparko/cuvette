suppressMessages(library(nlme))
d <- read.csv("/Volumes/T7/guided-analysis/data/bates2015-lme4-sleepstudy/sleepstudy.csv")
d$Subject <- factor(d$Subject)
ctl <- lmeControl(opt = "optim", maxIter = 200, msMaxIter = 200)
m1 <- lme(Reaction ~ Days, random = ~ Days | Subject, data = d, method = "ML", control = ctl)
m0 <- lme(Reaction ~ 1, random = ~ Days | Subject, data = d, method = "ML", control = ctl)
cat(R.version.string, "nlme", as.character(packageVersion("nlme")), "\n")
cat(sprintf("logLik full %.4f, reduced %.4f\n", logLik(m1), logLik(m0)))
cat(sprintf("lrt_chi2_days %.4f\n", 2 * (as.numeric(logLik(m1)) - as.numeric(logLik(m0)))))
print(anova(m0, m1))
