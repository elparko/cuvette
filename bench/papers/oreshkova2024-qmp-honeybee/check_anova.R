D <- Sys.getenv("GA_DATA", "/Volumes/T7/guided-analysis/data")
d <- file.path(D, "oreshkova2024-qmp-honeybee")
pool <- read.csv(file.path(d, "qmp_pooled_data.csv"), fileEncoding = "UTF-8-BOM")
hpg <- read.csv(file.path(d, "hpg_data.csv"), fileEncoding = "UTF-8-BOM")
cat(R.version.string, "\n")

cat("\n## Abdominal protein: aov(fb_mg ~ factor(age)*factor(treatment)*factor(replicate))\n")
m1 <- aov(fb_mg ~ factor(age) * factor(treatment) * factor(replicate), data = pool)
print(summary(m1))
cat(sprintf("p for age %.6e\n", summary(m1)[[1]][["Pr(>F)"]][1]))

cat("\n## Abdominal FAS activity: the same model on fb_nadph\n")
m2 <- aov(fb_nadph ~ factor(age) * factor(treatment) * factor(replicate), data = pool)
print(summary(m2))
cat("The paper prints F2,60 = 0.962 for treatment by replicate. 0.9616 is the mean square; the F is 1.2624.\n")

cat("\n## Acini area: aov(Average ~ factor(Age)*factor(Treatment)*factor(Replicate))\n")
m3 <- aov(Average ~ factor(Age) * factor(Treatment) * factor(Replicate), data = hpg)
print(summary(m3))

cat("\n## Acini area with type III sums of squares (the trap)\n")
suppressMessages(library(car))
op <- options(contrasts = c("contr.sum", "contr.poly"))
m3b <- lm(Average ~ factor(Age) * factor(Treatment) * factor(Replicate), data = hpg)
print(Anova(m3b, type = 3))
options(op)
cat("The acini design is unbalanced:\n")
print(table(hpg$Age, hpg$Treatment, hpg$Replicate))

cat("\n## Normalized FAS: Kruskal-Wallis and Dunn\n")
print(kruskal.test(fas ~ order, data = pool))
print(kruskal.test(fas ~ replicate, data = pool))
suppressMessages(library(FSA))
print(dunnTest(fas ~ factor(order), data = pool, method = "bonferroni")$res)
