suppressMessages(library(survival))
d <- read.csv("/Volumes/T7/guided-analysis/data/rossi1980-recidivism/rossi.csv")
m <- coxph(Surv(week, arrest) ~ fin + age + race + wexp + mar + paro + prio, data = d, ties = "efron")
s <- summary(m)$coefficients
lr <- survdiff(Surv(week, arrest) ~ fin, data = d)
zr <- cox.zph(m, transform = "rank", terms = FALSE)
zk <- cox.zph(m, transform = "km", terms = FALSE)
cat(R.version.string, "survival", as.character(packageVersion("survival")), "\n")
cat(sprintf("subjects %d events %d\n", m$n, m$nevent))
cat(sprintf("coef_fin %.4f coef_age %.4f coef_prio %.4f\n", s["fin", "coef"], s["age", "coef"], s["prio", "coef"]))
cat(sprintf("hazard_ratio_fin %.4f\n", s["fin", "exp(coef)"]))
cat(sprintf("p_fin %.4f\n", s["fin", "Pr(>|z|)"]))
cat(sprintf("concordance %.4f\n", m$concordance["concordance"]))
cat(sprintf("logrank_chi2_fin %.4f logrank_p_fin %.4f\n", lr$chisq, pchisq(lr$chisq, 1, lower.tail = FALSE)))
cat(sprintf("ph_test_p_age (cox.zph, rank transform, survival 3 score test) chisq %.3f p %.5f\n", zr$table["age", "chisq"], zr$table["age", "p"]))
cat(sprintf("ph_test_p_age (cox.zph, km transform, survival 3 score test) chisq %.3f p %.5f\n", zk$table["age", "chisq"], zk$table["age", "p"]))
sch <- residuals(m, type = "scaledsch")
tt <- rank(as.numeric(rownames(sch)))
r <- sch[, "age"]
e <- nrow(sch)
var_age <- vcov(m)["age", "age"]
tt <- tt - mean(tt)
stat <- (sum(tt * r))^2 / (e * var_age * sum(tt^2))
cat(sprintf("ph_test_p_age (Grambsch-Therneau 1994 approximation, rank transform, by hand) chisq %.3f p %.5f\n", stat, pchisq(stat, 1, lower.tail = FALSE)))
